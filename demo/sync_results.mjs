// Refresh the viewer without regenerating any of the images used by the model.
import { readFile, writeFile, access } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = dirname(fileURLToPath(import.meta.url));
const reportPath = resolve(root, process.argv[2] || '../solution/results/track_a_full/latest.json');
const gradesPath = resolve(root, process.argv[3] || '../solution/results/track_a_full/reference-review.json');
const context = { window: {} };
vm.runInNewContext(await readFile(resolve(root, 'data.js'), 'utf8'), context);
const data = context.window.DEMO;
const report = JSON.parse(await readFile(reportPath, 'utf8'));
const review = process.argv[3] ? JSON.parse(await readFile(gradesPath, 'utf8')) : {run_id:report.run_id,source:'human_review',grades:{}};
if (report.run_id !== review.run_id) throw Error('Grades belong to another run.');
const index = new Map(report.items.flatMap(item => item.decisions.map(d => [d.claimId, { item, d }])));
if (index.size !== data.claims.length || data.claims.some(c => !index.has(c.claimId)))
  throw Error('Run does not cover every viewer claim.');
for (const c of data.claims) {
  const { item, d } = index.get(c.claimId);
  if (item.id !== c.sceneId || d.statement !== c.statement) throw Error('Claim identity mismatch: ' + c.claimId);
  Object.assign(c, d, { run: report.run_id, models: item.records.flatMap(record =>
    record.decisions.filter(p => p.claimId === c.claimId).map(p => ({ ...p,
      modelId: record.modelId, model: record.returned_model || record.model, pass: record.pass }))) });
}
for (const item of report.items) {
  const scene = data.scenes.find(s => s.sceneId === item.id);
  for (const v of item.view_manifest) {
    const old = scene.views.find(view => view.name === v.name);
    if (!old || resolve(root, old.src).toLowerCase() !== resolve(v.file).toLowerCase())
      throw Error('Viewer/model image mismatch: ' + item.id + '/' + v.name);
    await access(v.file);
  }
  if (scene.views.length !== item.view_manifest.length) throw Error('Viewer has additional views not sent to model.');
}
data.generated = new Date().toISOString();
data.run_id = report.run_id;
data.grading = { ...review, grades: Object.fromEntries(Object.entries(review.grades || {}).filter(([id,g]) =>
  index.has(id) && ['supported','refuted','no_evidence'].includes(g.truth))) };
data.geometry.runs = [report.run_id];
data.geometry.models = [...new Set(data.claims.flatMap(c => c.models.map(m => m.model)))];
await writeFile(resolve(root, 'data.js'), '// generated by demo/sync_results.mjs\nwindow.DEMO = ' + JSON.stringify(data) + ';\n');
console.log(`Viewer updated: ${data.claims.length} claims, ${report.items.length} scenes, ${Object.keys(data.grading.grades).length} reference grades. Image bytes unchanged.`);
