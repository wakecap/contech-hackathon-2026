import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { aggregate } from '../solution/voting.mjs';
import { archiveRuns } from '../solution/run_history.mjs';

export function buildDataset(id, sources, claims, reference, fallbackPolicy) {
  const indexed=new Map();
  for (const source of sources) for (const item of source.items || []) {
    const records=item.records.filter(r=>r.modelId===id), planned=source.models?.find(m=>m.id===id);
    if(!records.length&&!planned)continue;
    const model={id,passes:planned?.passes||Math.max(1,...records.map(r=>r.pass)),weight:1};
    for(const c of claims.filter(c=>records.some(r=>r.decisions.some(d=>d.claimId===c.claimId)) || planned&&item.decisions.some(d=>d.claimId===c.claimId))) {
      if(indexed.has(c.claimId))continue;
      const d=aggregate(c.claimId,[model],records,{...(source.aggregation||fallbackPolicy),accept_low_confidence:true});
      const observations=records.flatMap(r=>r.decisions).filter(p=>p.claimId===c.claimId&&p.verdict===d.leading_verdict).sort((a,b)=>b.confidence-a.confidence);
      indexed.set(c.claimId,{...c,...d,observation:observations[0]?.observation||'',
        evidence_views:[...new Set(observations.flatMap(p=>p.views))],evidence:d.verdict&&d.verdict!=='no_evidence'?item.images:[],
        reasoning_effort:planned?.reasoning_effort||records[0]?.reasoning_effort||null,
        models:records.flatMap(r=>r.decisions.filter(p=>p.claimId===c.claimId).map(p=>({...p,modelId:id,model:r.returned_model||r.model,pass:r.pass}))),run:source.run_id});
    }
  }
  const report=sources[0],levels=[...new Set([...indexed.values()].map(c=>c.reasoning_effort||'not recorded'))];
  return {model_id:id,model_label:id==='luna'?'Luna':'DeepSeek',run_id:report?.run_id||id+'-unavailable',
    reasoning_level:levels.length===1?levels[0]:levels.length?'mixed':'not recorded',
    claims:claims.map(c=>indexed.get(c.claimId)||{...c,status:'pending',verdict:null,leading_verdict:null,scores:{},models:[],evidence_views:[],evidence:[],observation:'',run:null}),
    grading:{...reference,run_id:report?.run_id,reference_run_id:reference.run_id,grades:Object.fromEntries(Object.entries(reference.grades).filter(([claimId])=>indexed.has(claimId)))}};
}

async function main(){
  const root=dirname(fileURLToPath(import.meta.url)),solution=resolve(root,'../solution');
  const reports=await archiveRuns(join(solution,'results'),join(solution,'run_history'));
  const claims=JSON.parse(await readFile(resolve(root,'../data/track_a/claims.json'),'utf8')).claims;
  const reference={run_id:'manual-review',source:'human_review',grades:{}};
  const policy=JSON.parse(await readFile(join(solution,'config.full.json'),'utf8')).aggregation;
  const result={};
  for(const id of ['luna','deepseek']){
    const sources=reports.filter(r=>r.models?.some(m=>m.id===id)||r.items.some(i=>i.records.some(rec=>rec.modelId===id)));
    result[id]=buildDataset(id,sources,claims,reference,policy);
    result[id].runs=sources.map(r=>({...buildDataset(id,[r],claims,reference,policy),historical:true}));
  }
  await writeFile(join(root,'model-results.js'),'// generated by demo/model_results.mjs\nwindow.MODEL_RESULTS = '+JSON.stringify(result)+';\n');
  console.log(Object.fromEntries(Object.entries(result).map(([id,r])=>[id,{runs:r.runs.length,claims:r.claims.filter(c=>c.status!=='pending').length}])));
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))await main();
